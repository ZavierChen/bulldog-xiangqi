"""Compact notebook layout; runtime behaviour stays in App."""
import os,tkinter as tk
from tkinter import ttk
from branding import apply_brand,ROOT
from board_view import BoardView
from sandbox import Sandbox

def card(parent,title):
    frame=ttk.LabelFrame(parent,text=title,padding=12);return frame

def build_shell(app,root,engine_path):
    apply_brand(root);root.geometry('1060x800');root.minsize(940,720)
    style=ttk.Style(root);style.theme_use('clam')
    style.configure('.',font=('Microsoft YaHei',10),background='#f5f3f8',foreground='#2c2633')
    style.configure('TFrame',background='#f5f3f8');style.configure('TLabel',background='#f5f3f8')
    style.configure('TLabelframe',background='#f5f3f8',bordercolor='#ddd7e4')
    style.configure('TLabelframe.Label',font=('Microsoft YaHei',10,'bold'),foreground='#5a3972')
    style.configure('Muted.TLabel',foreground='#7b7186',font=('Microsoft YaHei',9))
    style.configure('Section.TLabel',font=('Microsoft YaHei',12,'bold'),foreground='#4d2e66')
    style.configure('TButton',padding=(12,7),background='#ffffff',bordercolor='#d8cfe0')
    style.configure('Small.TButton',padding=(8,5))
    style.configure('Accent.TButton',background='#653b81',foreground='white',bordercolor='#653b81',font=('Microsoft YaHei',10,'bold'))
    style.map('Accent.TButton',background=[('active','#7b5099'),('disabled','#b3a5be')])
    style.configure('TNotebook',background='#f5f3f8',borderwidth=0)
    style.configure('TNotebook.Tab',padding=(22,9));style.map('TNotebook.Tab',background=[('selected','#e8deef')],foreground=[('selected','#542e70')])
    root.configure(bg='#f5f3f8')
    header=tk.Frame(root,bg='#392345');header.pack(fill='x')
    try:
        app.brand_image=tk.PhotoImage(file=str(ROOT/'assets/bulldog-64.png'))
        tk.Label(header,image=app.brand_image,bg='#392345').pack(side='left',padx=(18,10),pady=8)
    except tk.TclError:pass
    titles=tk.Frame(header,bg='#392345');titles.pack(side='left',pady=12)
    tk.Label(titles,text='斗牛犬',bg='#392345',fg='white',font=('Microsoft YaHei',18,'bold')).pack(anchor='w')
    tk.Label(titles,text='连接棋局 · 自由摆棋 · 三选一提示',bg='#392345',fg='#cfc1d9',font=('Microsoft YaHei',9)).pack(anchor='w')
    tk.Label(header,text='Pikafish / 本地计算',bg='#392345',fg='#d4c2df',font=('Microsoft YaHei',9)).pack(side='right',padx=22)
    app.notebook=ttk.Notebook(root);app.notebook.pack(fill='both',expand=True,padx=10,pady=(8,10))
    connection=ttk.Frame(app.notebook,padding=12);app.notebook.add(connection,text='连接对局')
    body=ttk.Frame(connection);body.pack(fill='both',expand=True)
    left=ttk.Frame(body);left.pack(side='left',fill='both',expand=True,padx=(0,16))
    ttk.Label(left,textvariable=app.position_label,style='Section.TLabel').pack(anchor='w',pady=(0,7))
    app.board_view=BoardView(left,width=510,height=550);app.board_view.pack(fill='both',expand=True);app.canvas=app.board_view
    right=ttk.Frame(body,width=340);right.pack(side='right',fill='y');right.pack_propagate(False)
    controls=ttk.Frame(right);controls.pack(fill='x',pady=(0,12))
    app.connect_button=ttk.Button(controls,text='开始连接',command=app.start,style='Accent.TButton');app.connect_button.pack(side='left',fill='x',expand=True)
    ttk.Button(controls,text='停止',command=app.stop.set).pack(side='left',padx=(8,0))
    quick=card(right,'常用设置');quick.pack(fill='x',pady=(0,12))
    row=ttk.Frame(quick);row.pack(fill='x')
    ttk.Label(row,text='基础秒 / 步').pack(side='left');ttk.Spinbox(row,from_=1,to=30,width=4,textvariable=app.seconds).pack(side='left',padx=(10,5))
    row=ttk.Frame(quick);row.pack(fill='x',pady=(10,0));ttk.Label(row,text='无头像保底').pack(side='left')
    for choice in ('我方先手','对方先手'):ttk.Radiobutton(row,text=choice,value=choice,variable=app.fallback_first,command=app.fallback_changed).pack(side='left',padx=(5,0))
    ttk.Label(quick,text='下方固定为本方；有提示时自动接入。',style='Muted.TLabel').pack(anchor='w',pady=(8,0))
    estimate=card(right,'当前局面');estimate.pack(fill='x',pady=(0,12))
    ttk.Label(estimate,textvariable=app.analysis_title,wraplength=306,style='Muted.TLabel').pack(anchor='w')
    ttk.Label(estimate,textvariable=app.red_analysis,foreground='#ac2925',wraplength=306).pack(anchor='w',pady=(8,4))
    ttk.Label(estimate,textvariable=app.black_analysis,wraplength=306).pack(anchor='w')
    progress=card(right,'运行状态');progress.pack(fill='x')
    ttk.Label(progress,textvariable=app.thinking_text,wraplength=306).pack(anchor='w')
    ttk.Label(progress,textvariable=app.phase_text,wraplength=306,style='Muted.TLabel').pack(anchor='w',pady=5)
    ttk.Label(progress,textvariable=app.status,wraplength=306).pack(anchor='w')
    ttk.Button(right,text='把当前棋盘复制到沙盒',command=app.copy_to_sandbox).pack(fill='x',pady=12)
    app.sandbox=Sandbox(app.notebook,engine_path,lambda:app.threads.get(),can_analyze=lambda:not app.running)
    app.notebook.add(app.sandbox,text='沙盒摆棋')
    settings=ttk.Frame(app.notebook,padding=20);app.notebook.add(settings,text='设置与诊断')
    columns=ttk.Frame(settings);columns.pack(fill='x')
    engine=card(columns,'引擎与预判');engine.pack(side='left',fill='both',expand=True,padx=(0,12))
    row=ttk.Frame(engine);row.pack(fill='x',pady=(0,10))
    ttk.Label(row,text='CPU 线程').pack(side='left');ttk.Spinbox(row,from_=1,to=os.cpu_count() or 1,width=4,textvariable=app.threads).pack(side='left',padx=8)
    ttk.Button(row,text='预留 2 线程',command=lambda:app.threads.set(max(1,(os.cpu_count() or 1)-2)),style='Small.TButton').pack(side='left')
    ttk.Checkbutton(engine,text='GPU 加速棋子识别',variable=app.use_gpu).pack(anchor='w',pady=3)
    row=ttk.Frame(engine);row.pack(fill='x',pady=3)
    ttk.Checkbutton(row,text='对方回合后台预判',variable=app.ponder_enabled).pack(side='left')
    ttk.Combobox(row,textvariable=app.ponder_branches,values=(2,3,4,5),state='readonly',width=3).pack(side='left',padx=8)
    ttk.Label(row,text='分支').pack(side='left')
    ttk.Checkbutton(engine,text='预判稳定后休息（自适应限时）',variable=app.ponder_economical).pack(anchor='w',pady=3)
    ttk.Checkbutton(engine,text='开局后持续不占优时动态加时',variable=app.dynamic_time).pack(anchor='w',pady=3)
    rounds=card(columns,'续局与恢复');rounds.pack(side='left',fill='both',expand=True)
    row=ttk.Frame(rounds);row.pack(fill='x',pady=(0,8))
    ttk.Label(row,text='本次最多').pack(side='left');ttk.Spinbox(row,from_=1,to=999,width=5,textvariable=app.game_limit).pack(side='left',padx=8);ttk.Label(row,text='局').pack(side='left')
    ttk.Checkbutton(rounds,text='一直对战，直到停止',variable=app.unlimited).pack(anchor='w',pady=3)
    ttk.Checkbutton(rounds,text='窗口失焦后自动恢复连接',variable=app.auto_reconnect).pack(anchor='w',pady=3)
    row=ttk.Frame(rounds);row.pack(fill='x',pady=8)
    ttk.Label(row,text='异常兜底等待').pack(side='left');ttk.Combobox(row,textvariable=app.fallback_seconds,values=(30,60),state='readonly',width=4).pack(side='left',padx=8);ttk.Label(row,text='秒').pack(side='left')
    details=card(settings,'诊断详情');details.pack(fill='x',pady=18)
    for variable in (app.connection_text,app.ponder_text,app.budget_text,app.latency_text):
        ttk.Label(details,textvariable=variable,wraplength=900,style='Muted.TLabel').pack(anchor='w',pady=4)
    ttk.Label(settings,text='参数在下一次开始连接时读取。沙盒仅在点击电脑提示时计算；连接运行时不启动额外的沙盒分析。',wraplength=900,style='Muted.TLabel').pack(anchor='w')
